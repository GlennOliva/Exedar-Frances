create extension if not exists pgcrypto with schema extensions;

create table if not exists public.rsvps (
  id uuid primary key default gen_random_uuid(),
  first_name varchar(80) not null,
  last_name varchar(80) not null,
  email text not null unique check (email = lower(trim(email))),
  attendance varchar(16) not null check (attendance in ('attending', 'declining')),
  message varchar(1000),
  reminder_consent boolean not null default false,
  consent_at timestamptz,
  unsubscribed_at timestamptz,
  token_version uuid not null default gen_random_uuid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.idempotency_keys (
  key_hash char(64) primary key,
  rsvp_id uuid not null references public.rsvps(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.email_deliveries (
  id uuid primary key default gen_random_uuid(),
  rsvp_id uuid not null references public.rsvps(id) on delete cascade,
  email_type varchar(40) not null,
  status varchar(16) not null check (status in ('pending', 'sending', 'sent', 'failed', 'uncertain', 'skipped')),
  attempts integer not null default 0,
  smtp_message_id varchar(255),
  error_code varchar(80),
  scheduled_for timestamptz,
  claimed_at timestamptz,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists one_reminder_per_guest
  on public.email_deliveries (rsvp_id, email_type)
  where email_type like 'reminder:%';
create index if not exists eligible_reminder_guests
  on public.rsvps (attendance, reminder_consent, unsubscribed_at);

create table if not exists public.rate_limit_events (
  id bigint generated by default as identity primary key,
  scope varchar(40) not null,
  key_hash char(64) not null,
  created_at timestamptz not null default now()
);
create index if not exists rate_limit_lookup
  on public.rate_limit_events (scope, key_hash, created_at);

alter table public.rsvps enable row level security;
alter table public.idempotency_keys enable row level security;
alter table public.email_deliveries enable row level security;
alter table public.rate_limit_events enable row level security;
alter table public.rsvps force row level security;
alter table public.idempotency_keys force row level security;
alter table public.email_deliveries force row level security;
alter table public.rate_limit_events force row level security;

revoke all on table public.rsvps, public.idempotency_keys, public.email_deliveries, public.rate_limit_events from public, anon, authenticated;
revoke all on sequence public.rate_limit_events_id_seq from public, anon, authenticated;
grant all on table public.rsvps, public.idempotency_keys, public.email_deliveries, public.rate_limit_events to service_role;
grant usage, select on sequence public.rate_limit_events_id_seq to service_role;

create or replace function public.submit_rsvp(
  p_first_name text,
  p_last_name text,
  p_email text,
  p_attendance text,
  p_message text,
  p_reminder_consent boolean,
  p_key_hash text
)
returns table (
  id uuid,
  first_name varchar(80),
  last_name varchar(80),
  email text,
  attendance varchar(16),
  message varchar(1000),
  reminder_consent boolean,
  consent_at timestamptz,
  unsubscribed_at timestamptz,
  token_version uuid,
  created_at timestamptz,
  updated_at timestamptz,
  created boolean
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_rsvp public.rsvps%rowtype;
  v_created boolean := false;
begin
  perform pg_advisory_xact_lock(hashtextextended(p_key_hash, 0));

  select r.* into v_rsvp
  from public.idempotency_keys i
  join public.rsvps r on r.id = i.rsvp_id
  where i.key_hash = p_key_hash;

  if not found then
    insert into public.rsvps (first_name, last_name, email, attendance, message, reminder_consent, consent_at)
    values (
      trim(p_first_name), trim(p_last_name), lower(trim(p_email)), p_attendance,
      nullif(trim(p_message), ''), p_reminder_consent,
      case when p_reminder_consent then now() else null end
    )
    on conflict on constraint rsvps_email_key do nothing
    returning * into v_rsvp;

    if found then
      v_created := true;
    else
      select * into strict v_rsvp from public.rsvps where rsvps.email = lower(trim(p_email));
    end if;

    insert into public.idempotency_keys (key_hash, rsvp_id)
    values (p_key_hash, v_rsvp.id)
    on conflict (key_hash) do nothing;
  end if;

  return query select
    v_rsvp.id, v_rsvp.first_name, v_rsvp.last_name, v_rsvp.email::text,
    v_rsvp.attendance, v_rsvp.message, v_rsvp.reminder_consent,
    v_rsvp.consent_at, v_rsvp.unsubscribed_at, v_rsvp.token_version,
    v_rsvp.created_at, v_rsvp.updated_at, v_created;
end;
$$;

create or replace function public.consume_rate_limit(
  p_scope text,
  p_key_hash text,
  p_maximum integer,
  p_window_minutes integer
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_count integer;
begin
  perform pg_advisory_xact_lock(hashtextextended(p_scope || ':' || p_key_hash, 0));
  delete from public.rate_limit_events where created_at < now() - interval '7 days';
  select count(*) into v_count
  from public.rate_limit_events
  where scope = p_scope and key_hash = p_key_hash
    and created_at > now() - (greatest(1, least(p_window_minutes, 10080)) * interval '1 minute');
  if v_count >= greatest(1, p_maximum) then return false; end if;
  insert into public.rate_limit_events (scope, key_hash) values (p_scope, p_key_hash);
  return true;
end;
$$;

create or replace function public.update_managed_rsvp(
  p_id uuid,
  p_token_version uuid,
  p_attendance text,
  p_reminder_consent boolean
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_updated uuid;
  v_consent boolean := p_reminder_consent and p_attendance = 'attending';
begin
  update public.rsvps
  set attendance = p_attendance,
      reminder_consent = v_consent,
      consent_at = case
        when v_consent and (not reminder_consent or consent_at is null) then now()
        when v_consent then consent_at
        else null
      end,
      unsubscribed_at = case when v_consent then null else unsubscribed_at end,
      updated_at = now()
  where rsvps.id = p_id and rsvps.token_version = p_token_version
  returning rsvps.id into v_updated;
  return v_updated is not null;
end;
$$;

create or replace function public.unsubscribe_rsvp(p_id uuid, p_token_version uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare v_updated uuid;
begin
  update public.rsvps
  set reminder_consent = false,
      unsubscribed_at = coalesce(unsubscribed_at, now()),
      updated_at = now()
  where rsvps.id = p_id and rsvps.token_version = p_token_version
  returning rsvps.id into v_updated;
  return v_updated is not null;
end;
$$;

create or replace function public.claim_reminder_deliveries(
  p_email_type text,
  p_scheduled_for timestamptz,
  p_now timestamptz
)
returns table (id uuid, rsvp_id uuid)
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.email_deliveries
  set status = 'uncertain', error_code = 'STALE_SENDING_STATE', updated_at = p_now
  where status = 'sending' and claimed_at < p_now - interval '30 minutes';

  return query
  with claimed as (
    insert into public.email_deliveries (rsvp_id, email_type, status, scheduled_for, claimed_at)
    select r.id, p_email_type, 'sending', p_scheduled_for, p_now
    from public.rsvps r
    where r.attendance = 'attending'
      and r.reminder_consent = true
      and r.unsubscribed_at is null
      and r.created_at <= p_scheduled_for
      and r.consent_at is not null
      and r.consent_at <= p_scheduled_for
    on conflict do nothing
    returning email_deliveries.id, email_deliveries.rsvp_id
  )
  select claimed.id, claimed.rsvp_id from claimed;
end;
$$;

create or replace function public.mark_stale_email_deliveries(p_now timestamptz)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare v_count integer;
begin
  update public.email_deliveries
  set status = 'uncertain', error_code = 'STALE_SENDING_STATE', updated_at = p_now
  where status = 'sending' and claimed_at < p_now - interval '30 minutes';
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

